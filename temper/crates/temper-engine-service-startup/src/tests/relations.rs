#[derive(Clone, Copy, Debug, PartialEq, Eq)]
enum Kind {
    Follows,
    SetByTemper,
    Floor,
    CheckedTogether,
    HoldsAll,
    MayRefuseBatch,
}
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
enum Small {
    Same,
    /// The fixture supplies its own carriers, without stock-agent derivation.
    Carriers,
    /// The fixture supplies its own work-in-flight counts and ties.
    Counts,
}
#[derive(Clone, Copy)]
struct Profile {
    jig: config::Limits,
    own: limits::Limits,
    slots: u32,
}
#[derive(Debug)]
#[expect(clippy::struct_excessive_bools, reason = "independent properties of each settings relation and its check")]
struct Relation {
    name: &'static str,
    kind: Kind,
    design: &'static str,
    figure: &'static str,
    sources: &'static [&'static str],
    formula: fn(&Profile) -> u64,
    small: Small,
    minimum: bool,
    worker: bool,
    overload: Option<fn(&Profile) -> Override>,
    explicit: Option<u64>,
    implicit: bool,
    full_start: bool,
}
impl Relation {
    fn actual(&self, profile: &Profile) -> u64 {
        value(profile, self.figure)
    }
    fn required(&self, profile: &Profile) -> u64 {
        (self.formula)(profile)
    }
    fn holds(&self, profile: &Profile) -> bool {
        if !unit_rule(self, profile) {
            return false;
        }
        let actual = self.actual(profile);
        let required = self.required(profile);
        if self.minimum {
            return actual >= required;
        }
        match self.kind {
            Kind::Follows | Kind::SetByTemper | Kind::CheckedTogether => actual == required,
            Kind::Floor | Kind::HoldsAll => actual >= required,
            Kind::MayRefuseBatch => actual > 0,
        }
    }
}
// A unit file is not generated by startup. Check its rounding rule over the
// same resolved stop bounds; box-shell pins the shipped help's 660 seconds.
fn unit_rule(row: &Relation, p: &Profile) -> bool {
    if row.figure != "stop_bound_ms" {
        return true;
    }
    let stop = row.actual(p);
    let with_margin = stop.checked_add(30_000).expect("stop margin");
    let timeout = with_margin.div_ceil(60_000).checked_mul(60_000).expect("unit minute");
    timeout >= with_margin && timeout % 60_000 == 0 && timeout.saturating_sub(60_000) < with_margin
}
fn value(profile: &Profile, name: &str) -> u64 {
    if let Some(row) = config::names::find(name.as_bytes()) {
        return (row.value)(&profile.jig);
    }
    match name {
        "forge_component.kept_bytes" => profile.own.forge_component.kept_bytes,
        "worker.slots" => u64::from(profile.slots),
        "store.key_bytes" => u64::from(profile.jig.store.store.key),
        "store.answer_bytes" => u64::from(temper_protocol_store::v25::CEILINGS.answer_name_name),
        "store.goals" => u64::from(temper_protocol_store::v25::CEILINGS.tier_row_goals),
        "wire.landing_members" => 5,
        "store.tier_landings" => u64::from(temper_protocol_store::tier_landings_ceiling()),
        "store.landing_log" => u64::from(temper_protocol_store::v25::CEILINGS.landing_log_landings),
        "store.posted_comments" => u64::from(temper_protocol_store::v25::CEILINGS.tier_posting_comments),
        "stop_bound_ms" => skein_forge_client::stop_bound(&profile.own.forge.client).as_millis(),
        _ => (limits::find(name.as_bytes()).expect("relation names a limit").value)(&profile.own),
    }
}
fn item(name: &str, value: u64) -> Override {
    Override { name: name.as_bytes().into(), value, reason: b"settings relation mutation".as_slice().into() }
}
fn profile(resolved: &startup::Resolved) -> Profile {
    Profile { jig: resolved.jig, own: resolved.temper, slots: 0 }
}
fn resolved_profile(inputs: &startup::LimitInputs, jig: &[Override], temper: &[Override]) -> Profile {
    let mut p = profile(&startup::resolve_limits(inputs, jig, temper).expect("profile starts"));
    p.slots = input_slots(inputs);
    p
}
fn input_slots(inputs: &startup::LimitInputs) -> u32 {
    if !inputs.is_box {
        return 0;
    }
    let document =
        config::document(&inputs.document, &config::DocumentLimits { bytes: 1_048_576, tokens: 1_048_576, depth: 32 })
            .expect("fixture document");
    derived::slots(&document).expect("box worker slots")
}
fn stock() -> Profile {
    profile(&startup::resolve_limits(&super::limit_settings::inputs(), &[], &[]).expect("stock starts"))
}
fn small() -> Profile {
    Profile { jig: jig_protocol_config_fixtures::small(), own: temper_limits_fixtures::small(), slots: 3 }
}
fn check_small(profile: &Profile) {
    // The same owners as temper-service's the_small_profile_passes_each_domains_validity.
    assert!(temper_engine_domain_forge::valid(&profile.own.forge));
    assert!(temper_worker_domain_checkout::valid(&temper_worker_service::worker_settings::checkout(
        profile.own.checkout
    )));
    assert_eq!(
        temper_worker_protocol_git::check(
            &temper_worker_service::worker_settings::git_component(profile.own.git_component),
            &temper_worker_service::worker_settings::checkout(profile.own.checkout),
        ),
        Ok(())
    );
    let root = limits::engine(&profile.jig, &profile.own).expect("small's effective root");
    assert!(temper_engine_domain::valid(&root));
}
#[test]
fn shipped_profiles_hold_the_relation_table() {
    let rows = table::relations();
    let worker_inputs = super::limit_settings::inputs_for(true);
    let worker = resolved_profile(&worker_inputs, &[], &[]);
    for (name, profile) in [("stock", stock()), ("small", small())] {
        if name == "small" {
            check_small(&profile);
        }
        for row in &rows {
            let profile = if row.worker && name == "stock" { worker } else { profile };
            eprintln!("{name}: {} ({:?}; {})", row.name, row.kind, row.design);
            if name == "small" && row.small != Small::Same {
                // Explicit fixture overrides: judged by the owners above, not rederived.
                continue;
            }
            assert!(
                row.holds(&profile),
                "{name}: {} ({}) got {}, required {}",
                row.name,
                row.design,
                row.actual(&profile),
                row.required(&profile)
            );
        }
    }
}
