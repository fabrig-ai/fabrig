//! Shipped profiles as relations, not individual figures (testing/settings-tests.md, 2 and 6).
#![expect(
    clippy::disallowed_macros,
    clippy::disallowed_types,
    clippy::disallowed_methods,
    clippy::print_stderr,
    clippy::use_debug,
    reason = "focused relation tests name every generated case and inspect startup diagnostic strings"
)]
use crate::{limits, startup};
use jig_domain_core::settings::Override;
use jig_protocol_config as config;
use temper_service_core::derived;

mod mutations;
