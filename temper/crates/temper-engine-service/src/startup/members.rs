/// The names a shape's decoder takes, including the settings members it refuses.
pub fn names(shape: &str) -> impl Iterator<Item = &'static str> {
    let mut names = List::with_capacity(u32::try_from(MEMBERS.len()).expect("bounded configuration rows"));
    for row in &MEMBERS {
        if row.shape == shape {
            names.push(row.name).expect("one name per row");
        }
    }
    names.into_boxed().into_iter()
}

pub(crate) fn object(
    document: &skein_json::Document,
    at: u32,
    shape: &'static str,
) -> Result<Object, jig_protocol_config::What> {
    Object::shaped(document, at, shape, &MEMBERS)
}

