#[derive(Clone, Copy)]
enum Slot {
    Address,
    State,
    Code,
    ApprovalAddress,
    PageAddress,
    Port,
    Span,
    Number,
    Moment,
    Clock,
    Step,
    Label,
    Title,
    LogLine,
    End,
}
impl Slot {
    const fn kind(self) -> HoleKind {
        match self {
            Self::Number => HoleKind::Number,
            Self::Moment => HoleKind::Moment,
            Self::Address
            | Self::State
            | Self::Code
            | Self::ApprovalAddress
            | Self::PageAddress
            | Self::Port
            | Self::Span
            | Self::Clock
            | Self::Step
            | Self::Label
            | Self::Title
            | Self::LogLine
            | Self::End => HoleKind::Name,
        }
    }
    fn bytes(self, domain: &Limits) -> u32 {
        match self {
            Self::Step => crate::limits::STEP,
            Self::LogLine => crate::limits::LOG_LINE.saturating_mul(3),
            Self::End => 40,
            Self::Title => domain.client.domain.text,
            Self::Address => 64,
            Self::Code => 9,
            Self::ApprovalAddress => 95,
            // http://, the bounded authority, /tasks/ and twenty task digits.
            Self::PageAddress => 98,
            Self::Port => 5,
            Self::Span | Self::Label => 32,
            Self::Number => 20,
            Self::Moment | Self::Clock => 13,
            Self::State => 11, // "Out of date" is the longest state word.
        }
    }
}
