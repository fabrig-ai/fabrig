#[derive(Debug)]
pub struct Words {
    book: Phrasebook,
    notice_bytes: u32,
    view: temper_client_view::words::Words,
}
impl Words {
    /// The TUI's English phrases under its owner, with domain-bounded holes.
    pub fn english(view: temper_client_view::words::Words, domain: &Limits) -> Result<Words, Invalid> {
        let count = u32::try_from(ALL.len()).expect("the word count fits");
        let mut shapes = List::with_capacity(count);
        let mut phrases = List::with_capacity(count);
        let mut literal_bytes = 0_u32;
        let mut segment_count = 0_u32;
        for word in ALL {
            let (parts, names) = word.english();
            let mut holes = List::with_capacity(2);
            for name in names {
                holes.push(HoleShape { kind: name.kind(), bytes: name.bytes(domain) }).expect("at most two holes");
            }
            let mut segments = List::with_capacity(5);
            for (index, part) in parts.iter().enumerate() {
                literal_bytes = literal_bytes
                    .checked_add(u32::try_from(part.len()).ok().ok_or(Invalid::Overflow)?)
                    .ok_or(Invalid::Overflow)?;
                segments.push(Segment::Text(copy_of(part))).expect("at most five segments");
                if index < names.len() {
                    segments
                        .push(Segment::Hole {
                            index: u16::try_from(index).expect("two holes"),
                            kind: names.get(index).expect("hole has a shape").kind(),
                        })
                        .expect("at most five segments");
                }
            }
            let other = Form { class: PluralClass::Other, segments: segments.into_boxed() };
            let forms: Box<[Form]> = if word == Word::Needing {
                literal_bytes = literal_bytes.checked_add(10).ok_or(Invalid::Overflow)?;
                Box::new([
                    Form {
                        class: PluralClass::One,
                        segments: Box::new([
                            Segment::Text(copy_of(b"")),
                            Segment::Hole { index: 0, kind: HoleKind::Number },
                            Segment::Text(copy_of(b" needs you")),
                        ]),
                    },
                    other,
                ])
            } else {
                Box::new([other])
            };
            for form in &forms {
                segment_count = segment_count
                    .checked_add(u32::try_from(form.segments.len()).ok().ok_or(Invalid::Overflow)?)
                    .ok_or(Invalid::Overflow)?;
            }
            shapes
                .push(PhraseShape {
                    id: word.id(),
                    holes: holes.into_boxed(),
                    plural: if word == Word::Needing { Some(0) } else { None },
                })
                .expect("one shape per word");
            phrases.push(Phrase { id: word.id(), forms }).expect("one phrase per word");
        }
        let language = Language {
            plural: PluralRule::English,
            span_unit: SpanUnit::Seconds,
            wall: WallFormat::Clock,
            phrases: phrases.into_boxed(),
        };
        let limits = PhraseLimits {
            languages: 1,
            phrases: count,
            holes: 2,
            segments: segment_count,
            text_bytes: literal_bytes,
            hole_bytes: domain.client.domain.text.max(98).max(Slot::LogLine.bytes(domain)),
        };
        let book = Phrasebook::load(shapes.into_boxed(), Box::new([language]), &limits)?;
        Ok(Words { book, view, notice_bytes: domain.client.domain.text })
    }
    #[must_use]
    pub fn tell_lost(&self) -> Box<[u8]> {
        self.say(Word::TellLost, &[])
    }
    #[must_use]
    pub fn tell_long(&self, over: u32) -> Box<[u8]> {
        self.say(Word::TellLong, &[Hole::Number(u64::from(over))])
    }
    pub(crate) fn notice(&self, notice: &crate::Notice) -> Box<[u8]> {
        match notice {
            crate::Notice::Unknown { words } => {
                let bounded = skein_lib::bytes::utf8_prefix(
                    words,
                    usize::try_from(self.notice_bytes).expect("notice hole fits memory"),
                );
                self.say(Word::UnknownNotice, &[Hole::Name(copy_of(bounded))])
            }
            crate::Notice::Left { name, minutes, cost } => {
                let mut line = self.say(Word::LeftAfter, &[Hole::Name(name.clone()), Hole::Number(*minutes)]);
                if let Some(cost) = cost {
                    line = skein_lib::bytes::concat(&[
                        &line,
                        &self.say(Word::Separator, &[]),
                        &self.view.say(temper_client_view::words::Word::TeamCount, &[Hole::Number(*cost)]),
                    ]);
                }
                skein_lib::bytes::concat(&[&line, &self.say(Word::LeftNow, &[])])
            }
            crate::Notice::NoRole { project, words } => {
                let bounded = skein_lib::bytes::utf8_prefix(
                    words,
                    usize::try_from(self.notice_bytes).expect("notice hole fits memory"),
                );
                self.say(Word::NoRole, &[Hole::Name(project.clone()), Hole::Name(copy_of(bounded))])
            }
            crate::Notice::SigningIn => self.say(Word::SigningInNotice, &[]),
            crate::Notice::Filed { number, project } => {
                self.say(Word::FiledNotice, &[Hole::Number(u64::from(*number)), Hole::Name(copy_of(project))])
            }
            crate::Notice::Proposed => self.say(Word::ProposedNotice, &[]),
            crate::Notice::Theme { choice, terminal } => {
                let word = match choice {
                    crate::theme::ThemeChoice::Auto => match terminal {
                        Some(crate::Scheme::Light) => Word::ThemeNoticeAutoLight,
                        Some(crate::Scheme::Dark) => Word::ThemeNoticeAutoDark,
                        None => Word::ThemeNoticeAutoNone,
                    },
                    crate::theme::ThemeChoice::Light => Word::ThemeNoticeLight,
                    crate::theme::ThemeChoice::Dark => Word::ThemeNoticeDark,
                };
                self.say(word, &[])
            }
        }
    }
    #[must_use]
    pub fn say(&self, word: Word, holes: &[Hole]) -> Box<[u8]> {
        self.book.say(0, word.id(), holes).expect("checked TUI phrase and bounded holes").text
    }
    #[must_use]
    pub const fn view(&self) -> &temper_client_view::words::Words {
        &self.view
    }
}
