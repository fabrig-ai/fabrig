//! Only differing bytes are written; a stopped journey never reaches here (journey-walks.md, 5).
use std::{collections::BTreeSet, fs, io, path::Path};
use temper_client_walk_lines::{print, tui_print, walk::Client};

fn write(path: &Path, bytes: &[u8]) -> io::Result<bool> {
    match fs::read(path) {
        Ok(previous) if previous == bytes => return Ok(false),
        Ok(_) => {}
        Err(error) if error.kind() == io::ErrorKind::NotFound => {}
        Err(error) => return Err(error),
    }
    if let Some(parent) = path.parent() {
        fs::create_dir_all(parent)?;
    }
    fs::write(path, bytes)?;
    Ok(true)
}

pub(super) fn pages(directory: &Path, pages: &[print::Printed], in_place: bool) -> io::Result<bool> {
    fs::create_dir_all(directory)?;
    let mut changed = false;
    for page in pages {
        changed |= write(&directory.join(&page.name), page.document.as_bytes())?;
    }
    for entry in fs::read_dir(directory)? {
        let entry = entry?;
        let name = entry.file_name();
        let name = name.to_string_lossy();
        let numbered = name
            .strip_suffix(".html")
            .or_else(|| name.strip_suffix(".txt"))
            .is_some_and(|number| number.len() >= 2 && number.bytes().all(|byte| byte.is_ascii_digit()));
        if entry.file_type()?.is_file()
            && ((numbered && !pages.iter().any(|page| page.name == name)) || (in_place && name == "recording"))
        {
            fs::remove_file(entry.path())?;
            changed = true;
        }
    }
    Ok(changed)
}

pub(super) fn assets(repository: &Path, destination: &Path, client: Client) -> io::Result<bool> {
    let root = match client {
        Client::Web => crate::WEB,
        Client::Tui => crate::TUI,
    };
    // beside owns these generated bytes. Stage them so an in-place fresh print
    // doesn't rewrite even a shared file, including the overlay it preserves.
    let stage = tempfile::tempdir()?;
    let overlay = repository.join(root).join("overlay.css");
    if overlay.is_file() {
        fs::copy(overlay, stage.path().join("overlay.css"))?;
    }
    match client {
        Client::Web => print::beside(stage.path())?,
        Client::Tui => tui_print::beside(stage.path())?,
    }
    let mut changed = false;
    for entry in fs::read_dir(stage.path())? {
        let entry = entry?;
        changed |= write(&destination.join(root).join(entry.file_name()), &fs::read(entry.path())?)?;
    }
    if client == Client::Tui {
        return Ok(changed);
    }
    let mut visited = BTreeSet::new();
    for stylesheet in print::STYLESHEETS {
        let path = super::resolve(&repository.join(crate::WEB).join("journey").join(stylesheet))?;
        // An absent overlay is made empty by beside; other absent checkout
        // stylesheets aren't copied.
        if path.is_file() {
            changed |= copy(repository, destination, &path, &mut visited)?;
        }
    }
    Ok(changed)
}

fn copy(
    repository: &Path,
    destination: &Path,
    source: &Path,
    visited: &mut BTreeSet<std::path::PathBuf>,
) -> io::Result<bool> {
    let source = fs::canonicalize(source)?;
    if !visited.insert(source.clone()) {
        return Ok(false);
    }
    let relative = source.strip_prefix(repository).map_err(io::Error::other)?;
    let bytes = fs::read(&source)?;
    let mut changed = write(&destination.join(relative), &bytes)?;
    if source.extension().is_some_and(|extension| extension == "css") {
        let css = std::str::from_utf8(&bytes).map_err(io::Error::other)?;
        let mut rest = css;
        while let Some((_, after)) = rest.split_once("url(") {
            let Some((url, after)) = after.split_once(')') else { break };
            rest = after;
            let url = url.trim().trim_matches(['\'', '"']);
            if url.is_empty() || url.starts_with(['/', '#']) || url.contains(':') {
                continue;
            }
            let url = url.split(['?', '#']).next().unwrap_or(url);
            let parent = source.parent().ok_or_else(|| io::Error::other("stylesheet has no parent"))?;
            changed |= copy(repository, destination, &parent.join(url), visited)?;
        }
    }
    Ok(changed)
}
