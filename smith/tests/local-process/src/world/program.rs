//! Program-account stories keep only the fake's generated account files across
//! invocations, beside the ordinary chat store (smith/docs/design/testing.md, 2.1 and 4).
use super::{Ending, HostedProgram, How, Machine, Placement, Proc, World, process};
use crate::terminal::Action;
use skein_fake_llm_domain::api;
use skein_io::kernel::{Done, Fd, ServiceSignal};
use skein_lib::{Duration, Time};
use skein_sim::{Event, Pid, Sim, Summary, Text};
use smith_fake_claude::{LOGIN_FILE, OBSERVATIONS_FILE, STORY_FILE, Story};

#[derive(Default)]
pub(super) struct Files {
    generated: Vec<(Box<[u8]>, Vec<u8>)>,
}

impl Files {
    fn account() -> Vec<u8> {
        [process::PROGRAMS.strip_prefix(b"/").expect("absolute programs path"), b"/", process::ACCOUNT.as_bytes()]
            .concat()
    }

    pub(super) fn plant(&self, machine: &mut Machine, story: &Story) {
        let programs = process::PROGRAMS.strip_prefix(b"/").expect("absolute programs path");
        machine.files.make_directory(machine.master, programs, 0o700).expect("private programs directory");
        let root = machine.files.open(machine.master, programs, How::Directory).expect("programs directory");
        let account = process::ACCOUNT.as_bytes();
        machine.files.make_directory(root, account, 0o700).expect("private program account");
        let directory = machine.files.open(root, account, How::Directory).expect("program account");
        machine.files.close(root);
        let script = story.encode();
        for (name, bytes) in [(LOGIN_FILE.as_bytes(), b"claude.ai".as_slice()), (STORY_FILE.as_bytes(), &script)]
            .into_iter()
            .chain(self.generated.iter().map(|(name, bytes)| (name.as_ref(), bytes.as_slice())))
        {
            let file = machine.files.open(directory, name, How::Create { mode: 0o600 }).expect("program fixture file");
            machine.files.write(file, 0, bytes).expect("program fixture bytes");
            machine.files.close(file);
        }
        machine.files.close(directory);
    }

    pub(super) fn remember(&mut self, machine: &mut Machine) {
        const FILE_BYTES: u32 = 1 << 20;
        let directory = machine.files.open(machine.master, &Self::account(), How::Directory).expect("program account");
        self.generated.clear();
        for (kind, name) in machine.files.list(directory, 32, 4096).expect("bounded program files") {
            if kind != skein_fake_machine::Is::File || [LOGIN_FILE.as_bytes(), STORY_FILE.as_bytes()].contains(&&*name)
            {
                continue;
            }
            let file = machine.files.open(directory, &name, How::ReadNoFollow).expect("fake-generated program file");
            assert!(machine.files.stat(file).size <= u64::from(FILE_BYTES), "bounded fake-generated file");
            let bytes = machine.files.read(file, 0, FILE_BYTES).expect("observe generated bytes");
            machine.files.close(file);
            self.generated.push((name, bytes));
        }
        machine.files.close(directory);
    }
}

impl World {
    /// Start one unattended report in the same named chat, without a terminal line.
    pub fn exec(&mut self, prompt: &[u8], answer: &[u8]) {
        self.scenario.launch.headless = true;
        self.scenario.launch.headless_prompt = Some(prompt.into());
        self.scenario.commands = vec![Action::Wait(answer.into()), Action::Eof];
    }

    /// Use the spawned agent's program account. The story scripts status and
    /// print; the launch environment can be set in `scenario.launch.program`.
    pub fn on_program(&mut self, story: Story) {
        assert_eq!(self.scenario.launch.placement, Placement::Spawned, "program accounts spawn their agent");
        let ending = &mut self.scenario.ending;
        let (Ending::Report(text) | Ending::ReadReport(text)) = ending else { panic!("program report fixture") };
        *ending = Ending::ProgramReport { text: std::mem::take(text), workspace: self.scenario.launch.change };
        self.scenario.launch.program = Some(process::ProgramLaunch::default());
        self.program_story = Some(story);
    }

    /// Raw fake records, including status and print argv and environment names,
    /// shared by each invocation made with the same `Files`.
    #[must_use]
    pub fn program_log(&self) -> Vec<u8> {
        self.programs
            .borrow()
            .generated
            .iter()
            .find(|(name, _)| name.as_ref() == OBSERVATIONS_FILE.as_bytes())
            .map_or_else(Vec::new, |(_, bytes)| bytes.clone())
    }

    /// Interrupt the local host after invocation `number` (one-based) of `auth status` appends its observation.
    pub fn interrupt_on_program_status(&mut self, number: usize) {
        assert!(self.program_story.is_some() && number > 0, "a numbered program status in this invocation");
        self.program_interrupt = Some(InterruptOnStatus { remaining: number, trace_read: 0, sent: None });
    }

    /// Time from that interrupt to full settlement, checking that its status child was reaped.
    #[must_use]
    pub fn program_interrupt_settlement(&self) -> Duration {
        let outcome = self.outcome.as_ref().expect("settled world");
        let sent = self.program_interrupt.as_ref().and_then(|watch| watch.sent.as_ref()).expect("status interrupted");
        assert!(
            outcome.trace[sent.after..].iter().any(|entry| entry.pid == sent.parent
                && matches!(entry.event,
                    Event::Complete { kind: Summary::Wait { pidfd, reap: true }, result: Ok(Done::Exit(_)), .. }
                        if pidfd == sent.child
                )),
            "the parent reaped the interrupted status child's exit"
        );
        outcome.end.saturating_since(sent.at)
    }

    /// A Direct report whose provider can also answer a tool-free carry-over summary.
    pub fn direct_carry_over(&mut self, summary: &[u8], answer: &str) {
        use smith_agent_world::fixture::{calls, says};
        self.scenario.scripts = Some(Box::new([
            api::Script {
                cue: b"Summarise the work so far".as_slice().into(),
                turns: Box::new([says(Box::new([api::Line::Text { text: summary.into() }]), 1)]),
            },
            api::Script {
                cue: Box::new([]),
                turns: Box::new([calls(
                    Box::new([api::Line::Call {
                        name: b"finish".as_slice().into(),
                        arguments: serde_json::to_vec(
                            &serde_json::json!({"form":"report", "text":answer, "fields":{}}),
                        )
                        .expect("report arguments")
                        .into(),
                    }]),
                    1,
                )]),
            },
        ]));
    }
}

/// Watches the fake's append completion rather than inferring a check from elapsed time.
pub(super) struct InterruptOnStatus {
    remaining: usize,
    trace_read: usize,
    sent: Option<Sent>,
}

struct Sent {
    at: Time,
    after: usize,
    parent: Pid,
    child: Fd,
}

impl InterruptOnStatus {
    pub(super) fn observe(&mut self, sim: &Sim, pids: &[Pid], procs: &[Proc], controls: &skein_world::Controls) {
        if self.sent.is_some() {
            return;
        }
        let trace = sim.trace();
        for (index, entry) in trace.iter().enumerate().skip(self.trace_read) {
            // A status process appends exactly one record, its invocation.
            if !matches!(entry.event, Event::Complete { kind: Summary::Append { .. }, result: Ok(_), .. })
                || !pids
                    .iter()
                    .zip(procs)
                    .any(|(pid, proc)| *pid == entry.pid && matches!(proc, Proc::Claude(fake) if fake.is_status()))
            {
                continue;
            }
            self.remaining -= 1;
            if self.remaining == 0 {
                assert!(sim.service_running(entry.pid), "the observed status is still live");
                // This fixture runs one Claude invocation at a time. Its spawn completion
                // precedes the append; remember that parent's pidfd to identify the reap.
                let (parent, child) = trace[..index]
                    .iter()
                    .rev()
                    .find_map(|entry| match entry.event {
                        Event::Complete {
                            kind: Summary::Spawn { program, .. },
                            result: Ok(Done::Spawned { pidfd, .. }),
                            ..
                        } if program == Text::of(process::CLAUDE) => Some((entry.pid, pidfd)),
                        _ => None,
                    })
                    .expect("observed status has a parent and child descriptor");
                let host = procs.iter().position(|proc| matches!(proc, Proc::Local(_))).expect("local host");
                self.sent = Some(Sent { at: sim.now(), after: trace.len(), parent, child });
                controls.signal(host, ServiceSignal::Interrupt);
                break;
            }
        }
        self.trace_read = trace.len();
    }
}

pub(super) fn host_children(
    world: &mut skein_world::World<process::Proc, super::Run, Machine>,
    launch: &process::Launch,
) -> u32 {
    let fake = smith_fake_claude::hosted(process::CLAUDE);
    world.host_startup(
        HostedProgram { program: fake.program, make: process::make_fake, instances: 4, operations: fake.operations },
        process::fake_roots,
        process::fake_appends,
    );
    world.host(HostedProgram {
        program: process::RELAY.into(),
        make: process::make_relay,
        instances: 2,
        operations: smith_agent_shell::relay::operations(),
    });
    let config = smith_agent_shell::config::from_value(process::agent_document(launch)).expect("program document");
    smith_agent_service::program_operations(&config.service).expect("configured program operation bound")
}
