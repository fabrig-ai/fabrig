//! Frozen generated code and bytes follow skein/docs/design/data/codec/README.md, section 6.

use std::{fs, path::Path};

use skein_codegen::{Output, generate, parse, tests_main};

const REGENERATE: &str =
    "run SKEIN_CODEGEN_WRITE=1 cargo nextest run -p smith-codecs-world --test suite -E 'test(/^drift::/)'";

#[test]
fn charter_schema_matches_generated_code_and_all_goldens() {
    assert_family("charter", 4);
    assert_family("charter", 5);
}

#[test]
fn transcript_schema_matches_generated_code_and_all_goldens() {
    assert_family("transcript", 6);
    assert_family("transcript", 7);
}

#[test]
fn channel_schema_matches_generated_code_and_all_goldens() {
    assert_family("channel", smith_channel::wire::VERSION);
}

fn assert_family(family: &str, version: u16) {
    let root = skein_scratch::paths::tree().join(format!("crates/smith-{family}"));
    let schema = if family == "charter" && version == 4 {
        root.join("schema/kept/smith-charter-v4.schema")
    } else {
        root.join(format!("schema/{family}-v{version}.schema"))
    };
    let source = fs::read_to_string(schema).expect("schema source");
    let output = generate(&parse(&source).expect("schema valid"));
    let module = format!("v{version}");
    if family == "transcript" && version == 6 {
        check_artifact(&root.join("src/generated/v6.rs"), output.rust.as_bytes());
    } else {
        let modules: &[&str] = if family == "charter" { &["v4", "v5"] } else { &[&module] };
        check_generated(&root, &module, &format!("smith_{family}::{module}"), modules, &output);
    }
    let goldens = root.join(format!("golden/v{version}"));
    for golden in output.goldens {
        check_artifact(&goldens.join(&golden.name), &golden.bytes);
    }
}

use crate::support::events;

#[test]
fn event_records_and_every_listed_value_match_frozen_version_four_goldens() {
    let root = skein_scratch::paths::tree().join("crates/smith-events/golden/v4");
    let limits = smith_events::Limits { items: 8, ..smith_events_fixtures::SMALL };
    let samples = events::samples();
    assert_eq!(fs::read_dir(&root).expect("event goldens").count(), samples.len(), "every golden is covered");
    check_event_goldens(&root, &limits, &samples);
}

fn check_event_goldens(
    root: &Path,
    limits: &smith_events::Limits,
    rows: &[(&str, smith_events::Record, smith_events::Capture)],
) {
    for (name, record, capture) in rows {
        let path = root.join(format!("{name}.jsonl"));
        if std::env::var_os("SKEIN_CODEGEN_WRITE").as_deref() == Some(std::ffi::OsStr::new("1")) {
            let encoded = smith_events::write(record, capture, limits).expect("bounded fixture").expect("event");
            check_artifact(&path, &encoded);
        }
        let frozen = fs::read(&path).expect("frozen event golden");
        let ceiling = u32::try_from(frozen.len()).expect("golden length");
        let encoded = smith_events::write_with_ceiling(record, capture, limits, ceiling)
            .expect("bounded fixture")
            .expect("event");
        assert_eq!(encoded.as_ref(), frozen, "event {name} drifted");
        let decoded =
            smith_events::read_with_ceiling(&frozen, limits, ceiling).expect("valid golden").expect("known record");
        let rewritten = smith_events::write_with_ceiling(&decoded, capture, limits, ceiling)
            .expect("bounded decoded fixture")
            .expect("event");
        assert_eq!(rewritten.as_ref(), frozen, "golden {name} reads back");
    }
}

#[test]
fn local_store_schema_and_layout_fingerprints_match_committed_code_and_goldens() {
    let crates = skein_scratch::paths::tree().join("crates");
    let root = crates.join("smith-local-protocol");
    let source = fs::read_to_string(root.join("schema/local-store-v1.schema")).expect("local store schema");
    let schema = parse(&source).expect("local store schema valid");
    let output = generate(&schema);
    check_generated(
        &crates.join("smith-local-protocol-codec"),
        "local_store_v1",
        "smith_local_protocol_codec::local_store_v1",
        &["local_store_v1"],
        &output,
    );
    let goldens = root.join("golden/v1");
    for golden in output.goldens {
        check_artifact(&goldens.join(&golden.name), &golden.bytes);
    }
    let store = skein_codec::schema::parse(source.as_bytes())
        .expect("store fingerprint schema")
        .fingerprints()
        .family()
        .digest();
    let transcript = fs::read(crates.join("smith-transcript/schema/transcript-v7.schema")).expect("transcript schema");
    let transcript = skein_codec::schema::parse(&transcript)
        .expect("transcript fingerprint schema")
        .fingerprints()
        .family()
        .digest();
    let layouts = format!(
        "// Generated by the local-store drift test. Do not edit.\n\npub const STORE: [u8; 32] = {store:?};\n\npub const TRANSCRIPT: [u8; 32] = {transcript:?};\n"
    );
    let path = root.join("src/generated/layouts.rs");
    check_artifact(&path, layouts.as_bytes());
}

fn check_generated(root: &Path, file: &str, records: &str, modules: &[&str], output: &Output) {
    check_artifact(&root.join(format!("src/generated/{file}.rs")), output.records.as_bytes());
    check_artifact(&root.join(format!("tests/generated/{file}.rs")), output.tests.text(records).as_bytes());
    check_artifact(&root.join("tests/generated/main.rs"), tests_main(modules).as_bytes());
}

fn check_artifact(path: &Path, expected: &[u8]) {
    if std::env::var_os("SKEIN_CODEGEN_WRITE").as_deref() == Some(std::ffi::OsStr::new("1")) {
        fs::create_dir_all(path.parent().expect("artifact directory")).expect("artifact directory");
        fs::write(path, expected).expect("write generated artifact");
    }
    assert!(fs::read(path).ok().as_deref() == Some(expected), "{} drifted; {REGENERATE}", path.display());
}
