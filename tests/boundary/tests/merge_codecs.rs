//! The merge job's codec list names every generated family and its texts in order
//! (temper/docs/design/protocol/tooling.md, 4.1; skein/docs/design/data/codec/README.md, 4).

use std::collections::BTreeSet;
use std::fs;
use std::path::{Component, Path};
use std::process::Command;

fn relative(path: &str) -> bool {
    !path.is_empty() && Path::new(path).components().all(|part| matches!(part, Component::Normal(_)))
}

#[test]
fn the_merge_list_reproduces_every_generated_codec() {
    let root = skein_scratch::paths::workspace();
    let output = Command::new("git").args(["ls-files", "-z"]).current_dir(&root).output().expect("list tracked files");
    assert!(output.status.success(), "git ls-files: {}", String::from_utf8_lossy(&output.stderr));
    let mut tracked = BTreeSet::new();
    for raw in output.stdout.split(|byte| *byte == 0).filter(|path| !path.is_empty()) {
        let path = std::str::from_utf8(raw).expect("UTF-8 tracked path");
        if path.contains("/src/generated/") {
            let text = fs::read_to_string(root.join(path)).expect("read tracked generated file");
            if text.lines().next().is_some_and(|line| line.starts_with("// Generated by skein-codegen from")) {
                tracked.insert(path.to_owned());
            }
        }
    }

    let text = fs::read_to_string(root.join("tools/merge/codecs.txt")).expect("read codec list");
    let mut listed = BTreeSet::new();
    let mut previous = None;
    for line in text.lines() {
        let line = line.split('#').next().expect("line before comment");
        let mut paths = line.split_whitespace();
        let Some(module) = paths.next() else { continue };
        assert!(relative(module), "{module}: repository-relative module path");
        assert!(previous.is_none_or(|path| path < module), "{module}: sorted, unique module paths");
        previous = Some(module);
        listed.insert(module.to_owned());
        let mut schemas: Vec<_> = paths.collect();
        let maps = if schemas
            .last()
            .is_some_and(|path| Path::new(path).extension().is_some_and(|extension| extension == "maps"))
        {
            let path = schemas.pop().expect("last maps path");
            assert!(relative(path), "{path}: repository-relative maps path");
            Some(fs::read_to_string(root.join(path)).unwrap_or_else(|why| panic!("{path}: {why}")))
        } else {
            None
        };
        let first = schemas.first().expect("each module lists at least one schema text");
        let stem = Path::new(first).file_stem().expect("schema stem").to_str().expect("UTF-8 stem");
        let (stem, _) = stem.rsplit_once("-v").expect("schema version suffix");
        assert_eq!(
            Path::new(module).file_name().expect("module file name"),
            format!("{}.rs", stem.replace('-', "_")).as_str()
        );
        let mut source = String::new();
        for schema in schemas {
            assert!(relative(schema), "{schema}: repository-relative schema path");
            source.push_str(&fs::read_to_string(root.join(schema)).unwrap_or_else(|why| panic!("{schema}: {why}")));
        }
        let schema = skein_codegen::parse(&source).unwrap_or_else(|why| panic!("{module}: {why:?}"));
        let generated = match maps {
            Some(maps) => skein_codegen::translate(&schema, &maps).unwrap_or_else(|why| panic!("{module}: {why}")),
            None => skein_codegen::generate(&schema).records,
        };
        let committed = fs::read_to_string(root.join(module)).unwrap_or_else(|why| panic!("{module}: {why}"));
        assert!(generated == committed, "{module}: listed schema texts do not reproduce committed module");
    }
    assert_eq!(listed, tracked, "the list names every tracked skein-codegen module and nothing else");
}
