//! Only generated code implements codec traits (skein/docs/design/data/codec/README.md, 4, and skein/docs/design/data/codec/golden.md, 1).

use std::{fs, path::Path, process::Command};

fn findings(path: &str, source: &str) -> Vec<String> {
    if Path::new(path).starts_with("skein/crates/skein-codec")
        || source.lines().next().is_some_and(|line| line.starts_with("// Generated "))
    {
        return Vec::new();
    }
    fabrig_boundary::codec_implementation_lines(source)
        .into_iter()
        .map(|line| format!("{path}:{line}: only generated code may implement Record or Field"))
        .collect()
}

#[test]
fn handwritten_codec_implementations_are_refused_at_their_lines() {
    for source in [
        "\nimpl Record for Handwritten {}",
        "\nimpl skein_codec::Record for Handwritten {}",
        "\nimpl<L, T> Field<L, T> for Handwritten {}",
        "\nimpl<L, T: Other<Inner<T>>>\n    skein_codec::field::Field<L, T> for Handwritten {}",
        "\nimpl<L: Fn() -> Other<T>, T> Field<L, T> for Handwritten {}",
        "\nimpl Field<Limits, Value> for skein_codec::field::U8 {}",
        "\nmacro_rules! handwritten { () => { impl ::skein_codec::Record for Handwritten {} } }",
    ] {
        assert_eq!(
            findings("some/src/lib.rs", source),
            ["some/src/lib.rs:2: only generated code may implement Record or Field"],
            "{source}"
        );
    }
}

#[test]
fn only_codec_crate_and_generated_files_are_exempt() {
    let source = "impl skein_codec::Record for Handwritten {}";
    assert_eq!(findings("skein/crates/skein-codec/src/record.rs", source), Vec::<String>::new());
    assert_eq!(findings("some/fixture.rs", &format!("// Generated by skein-codegen.\n{source}")), Vec::<String>::new());
    for (path, source) in [
        ("skein/crates/skein-codec-other/src/lib.rs", source.to_owned()),
        ("some/src/generated/records.rs", source.to_owned()),
        ("some/src/lib.rs", format!("// Hand-written\n// Generated by skein-codegen.\n{source}")),
    ] {
        assert_eq!(findings(path, &source).len(), 1, "{path}: {source}");
    }
    assert_eq!(
        findings(
            "some/src/lib.rs",
            r#"
// impl Record for Comment {}
/* impl Field<(), ()> for Comment {} */
const TEXT: &str = "impl skein_codec::Record for StringLiteral {}";
const RAW: &str = r"impl Field<(), ()> for RawLiteral {}";
impl<T: Record> Other for Wrapper<T> {}
impl Record { fn inherent() {} }
"#,
        ),
        Vec::<String>::new()
    );
}

#[test]
fn codec_traits_are_implemented_only_by_the_codec_crate_and_generated_code() {
    let root = skein_scratch::paths::workspace();
    let output = Command::new("git")
        .args(["ls-files", "-z", "--", "*.rs"])
        .current_dir(&root)
        .output()
        .expect("list tracked Rust files");
    assert!(output.status.success(), "git ls-files: {}", String::from_utf8_lossy(&output.stderr));
    let mut failures = Vec::new();
    for raw in output.stdout.split(|byte| *byte == 0).filter(|path| !path.is_empty()) {
        let path = std::str::from_utf8(raw).expect("UTF-8 tracked path");
        let source = fs::read_to_string(root.join(path)).unwrap_or_else(|why| panic!("{path}: {why}"));
        failures.extend(findings(path, &source));
    }
    assert!(failures.is_empty(), "{}", failures.join("\n"));
}
