//! Named override limits (jig/docs/design/protocol/limits.md).

/// What a named limit counts (protocol/limits.md).
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum Unit {
    Count,
    Bytes,
    Milliseconds,
}

/// One limit an override may name.
#[derive(Clone, Copy, Debug)]
pub struct Name {
    /// Its dotted name, as `limits.overrides` names it.
    pub name: &'static str,
    pub unit: Unit,
    /// What it bounds, one sentence of at most 120 bytes.
    pub line: &'static str,
    /// Its value in the limits the parser fills, including the small profile for reference pages.
    pub value: fn(&crate::Limits) -> u64,
}

