/// The names a shape's decoder takes, including gone members which it refuses.
pub fn names(shape: &str) -> impl Iterator<Item = &'static str> {
    let mut names = List::with_capacity(u32::try_from(MEMBERS.len()).expect("static members count fits u32"));
    for member in &MEMBERS {
        if member.shape == shape {
            names.push(member.name).expect("at most one name per member");
        }
    }
    names.into_boxed().into_iter()
}

#[cfg(debug_assertions)]
pub(crate) fn contains(shape: &str, name: &[u8]) -> bool {
    for member in &MEMBERS {
        if member.shape == shape && member.name.as_bytes() == name {
            return true;
        }
    }
    false
}
