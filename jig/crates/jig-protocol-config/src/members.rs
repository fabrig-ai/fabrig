//! Configuration document members by shape (jig/docs/design/protocol/configuration.md, 3, 4 and 9).
use skein_lib::List;

/// A shape of the configuration document, and every path it is read at.
#[derive(Clone, Copy, Debug)]
pub struct Shape {
    pub name: &'static str,
    pub paths: &'static [&'static str],
    pub line: &'static str,
}

/// One member of a configuration document shape.
#[derive(Clone, Copy, Debug)]
pub struct Member {
    pub shape: &'static str,
    pub name: &'static str,
    /// Its type as the reference page prints it.
    pub kind: &'static str,
    /// Its bound as the reference page prints it, empty for none.
    pub bound: &'static str,
    pub required: bool,
    /// What it sets, one sentence of at most 160 bytes.
    pub line: &'static str,
    /// A member gone to the store: where it went, as its refusal says it.
    pub gone: Option<&'static str>,
}

