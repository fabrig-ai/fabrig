"""Delivery checks for temper/docs/design/protocol/configuration.md, 13.9."""
from dataclasses import dataclass
from pathlib import Path
import shlex
import shutil
import subprocess
import sys
import tempfile
import unittest


ROOT = Path(__file__).resolve().parents[2]
TREES = ('skein', 'smith', 'jig', 'temper', 'hearth')
LIB = 'temper/crates/a/src/lib.rs'
ONE_CRATE = (
    ('write', LIB, 'pub const X: u8 = 1;\n'),
    ('write', 'temper/crates/a/src/new.rs', 'pub const NEW: u8 = 0;\n'),
    ('move', 'temper/crates/a/src/old.rs', 'temper/crates/a/src/renamed.rs'),
    ('write', 'smith/docs/a.md', '# Changed\n'),
)
CRATE_FORMAT = ('--check temper/crates/a/src/lib.rs temper/crates/a/src/new.rs '
                'temper/crates/a/src/renamed.rs',)


@dataclass(frozen=True)
class Row:
    name: str
    edits: tuple
    runs: int
    success: bool
    rustfmt: tuple
    counted: tuple
    error: str = ''


ROWS = (
    Row('documents only', (
        ('write', 'temper/docs/a.md', '# Changed\n'),
        ('write', 'smith/docs/new.md', '# New\n'),
        ('write', 'README.md', '# Changed\n'),
    ), 1, True, (), ()),
    Row('one crate', ONE_CRATE, 1, True, CRATE_FORMAT, ('temper',)),
    Row('misformatted', (('write', LIB, '// misformatted\n'),),
        1, False, ('--check ' + LIB,), ()),
    Row('raised count', (('write', LIB, 'const WORDS: &str = "max_out";\n'),),
        1, False, ('--check ' + LIB,), ('temper',), 'max_out: count 1, baseline 0'),
    Row('passed tree', ONE_CRATE, 2, True, (), ()),
    Row('generated', (
        ('write', LIB, 'pub const X: u8 = 1;\n'),
        ('write', 'temper/crates/a/src/generated/v1.rs',
         '// Generated by skein-codegen from sample 1. Do not edit.\n// misformatted\n'),
        ('write', 'temper/crates/a/src/every/v1.rs',
         '// Generated by skein-codegen from sample 1. Do not edit.\n// misformatted\n'),
    ), 1, True, ('--check ' + LIB,), ('temper',)),
    Row("a tree's baseline", (('append', 'smith/scripts/old-forms.txt', '# note\n'),),
        1, True, (), ('smith',)),
    Row('the shared counter', (('append', 'tools/old_forms/old_forms.py', '# note\n'),),
        1, True, (), TREES),
)


def write(path, content):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding='utf-8')


def git(repository, env, *args):
    return subprocess.run(['git', *args], cwd=repository, env=env,
                          stdin=subprocess.DEVNULL, check=True, capture_output=True)


def prepare(job):
    env = {'PATH': f'{job}/bin:/usr/bin:/bin', 'HOME': str(job),
           'LANG': 'C.UTF-8', 'PRE_PR_LOG': str(job)}
    programs = {
        'rustfmt': 'printf \'%s\\n\' "$*" >> "$PRE_PR_LOG/rustfmt.log"\n'
                   'for file in "$@"; do\n'
                   '    if [ -f "$file" ] && grep -qw misformatted "$file"; then exit 1; fi\n'
                   'done\nexit 0\n',
        'cargo': 'printf \'%s\\n\' "$*" >> "$PRE_PR_LOG/cargo.log"\nexit 1\n',
        'python3': 'printf \'%s %s\\n\' "$PWD" "$*" >> "$PRE_PR_LOG/python3.log"\n'
                   f'exec {shlex.quote(sys.executable)} "$@"\n',
    }
    for name, body in programs.items():
        program = job / 'bin' / name
        write(program, '#!/bin/sh\n' + body)
        program.chmod(0o755)
    repository = job / 'fabrig'
    repository.mkdir()
    git(repository, env, 'init', '-q', '-b', 'main')
    git(repository, env, 'config', 'user.name', 'Pre-pr test')
    git(repository, env, 'config', 'user.email', 'pre-pr@example.test')
    git(repository, env, 'config', 'commit.gpgsign', 'false')
    for name in ('.temper/pre-pr', 'tools/old_forms/old_forms.py'):
        target = repository / name
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(ROOT / name, target)
    for tree in TREES:
        scripts = repository / tree / 'scripts'
        scripts.mkdir(parents=True)
        shutil.copy2(ROOT / 'temper/scripts/old_forms.py', scripts / 'old_forms.py')
        write(scripts / 'old-forms.txt', '# Baseline\nmax_out 0\nJournalRoom 0\n'
              'takes 0\nworst_case 0\ncomment:actual 0\ncomment:genuine 0\n')
        write(repository / tree / 'crates/a/src/lib.rs', 'pub const X: u8 = 0;\n')
        write(repository / tree / 'docs/a.md', '# A\n')
    write(repository / 'temper/crates/a/src/old.rs', 'pub const OLD: u8 = 0;\n')
    for path in ('generated/v1.rs', 'every/v1.rs'):
        write(repository / 'temper/crates/a/src' / path,
              '// Generated by skein-codegen from sample 1. Do not edit.\n')
    write(repository / 'README.md', '# A\n')
    git(repository, env, 'add', '.')
    git(repository, env, 'commit', '-qm', 'Seed delivery checks')
    return repository, env


def log(job, name):
    path = job / (name + '.log')
    return path.read_text(encoding='utf-8').splitlines() if path.exists() else []


class PrePr(unittest.TestCase):
    def test_delivery_increment(self):
        for row in ROWS:
            with self.subTest(row.name), tempfile.TemporaryDirectory(prefix='pre-pr-') as temporary:
                job = Path(temporary)
                repository, env = prepare(job)
                for action, name, content in row.edits:
                    if action == 'move':
                        git(repository, env, 'mv', name, content)
                    elif action == 'append':
                        path = repository / name
                        write(path, path.read_text(encoding='utf-8') + content)
                    else:
                        write(repository / name, content)
                index = (repository / '.git/index').read_bytes()
                for run in range(row.runs):
                    before_format = len(log(job, 'rustfmt'))
                    before_python = len(log(job, 'python3'))
                    result = subprocess.run(['fabrig/.temper/pre-pr'], cwd=job, env=env,
                                            stdin=subprocess.DEVNULL, capture_output=True)
                    self.assertFalse((job / 'cargo.log').exists(), 'the check must not call cargo')
                    if run < row.runs - 1:
                        self.assertEqual(result.returncode, 0, result.stderr.decode())
                        self.assertEqual(tuple(log(job, 'rustfmt')[before_format:]), CRATE_FORMAT)
                        self.assertTrue((repository / '.git/pre-pr-passed').is_file())
                self.assertEqual(result.returncode == 0, row.success, result.stderr.decode())
                self.assertEqual(tuple(log(job, 'rustfmt')[before_format:]), row.rustfmt)
                counters = [Path(line.split(' ', 1)[0]).name
                            for line in log(job, 'python3')[before_python:]
                            if line.endswith(' scripts/old_forms.py')]
                self.assertEqual(tuple(counters), row.counted)
                if row.error:
                    self.assertIn(row.error, result.stderr.decode())
                if not row.success:
                    self.assertFalse((repository / '.git/pre-pr-passed').exists())
                self.assertEqual((repository / '.git/index').read_bytes(), index)


if __name__ == '__main__':
    unittest.main()
