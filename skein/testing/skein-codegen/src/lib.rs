/// One schema version of a family.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Schema {
    pub family: String,
    pub version: u16,
    pub declarations: Vec<Declaration>,
}

/// A record or enumeration in declaration order.
#[derive(Clone, Debug, PartialEq, Eq)]
pub enum Declaration {
    Record(Record),
    Enum(Enumeration),
}

/// An ordered group of fields, optionally with a version prefix.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Record {
    pub line: usize,
    pub name: String,
    pub versioned: bool,
    pub fields: Vec<Field>,
}

/// An ordered group of variants, each holding at most one earlier record.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Enumeration {
    pub line: usize,
    pub name: String,
    pub variants: Vec<Variant>,
}

/// A named field of a record.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Field {
    pub line: usize,
    pub name: String,
    pub ty: Type,
}

/// A named variant with an optional record payload.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Variant {
    pub line: usize,
    pub name: String,
    pub record: Option<String>,
    /// Whether the record is held in a box without changing its wire bytes.
    pub boxed: bool,
}

/// A field's bounded wire type.
#[derive(Clone, Debug, PartialEq, Eq)]
pub enum Type {
    U8,
    U16,
    U32,
    U64,
    Bool,
    Duration,
    Fixed(u32),
    Bytes(u32),
    Secret(u32),
    Text(u32),
    List(u32, Box<Type>),
    Option(Box<Type>),
    Named(String),
}

/// Generated Rust for one schema version.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Output {
    pub rust: String,
    pub goldens: Vec<Golden>,
}

/// Frozen wire bytes for one generated test value.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Golden {
    pub name: String,
    pub bytes: Vec<u8>,
}

fn uses_box(ty: &Type) -> bool {
    match ty {
        Type::Bytes(_) | Type::Secret(_) | Type::Text(_) => true,
        Type::List(_, item) | Type::Option(item) => uses_box(item),
        Type::U8
        | Type::U16
        | Type::U32
        | Type::U64
        | Type::Bool
        | Type::Duration
        | Type::Fixed(_)
        | Type::Named(_) => false,
    }
}

fn uses_list(ty: &Type) -> bool {
    match ty {
        Type::List(_, _) => true,
        Type::Option(item) => uses_list(item),
        Type::U8
        | Type::U16
        | Type::U32
        | Type::U64
        | Type::Bool
        | Type::Duration
        | Type::Fixed(_)
        | Type::Bytes(_)
        | Type::Secret(_)
        | Type::Text(_)
        | Type::Named(_) => false,
    }
}

/// The names a generated module's bounds take (programming-model.md, 6.3) while each
/// tree moves its modules (wave 3).
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Names {
    /// `worst_case_bytes`, `worst_case_heap`, their `_within` forms and numbered helpers,
    /// and `List::worst_case` for a list's price: today's output, byte for byte.
    WorstCase,
    /// `encoded_bound`, `decoded_bound`, `encoded_bound_within`, `decoded_bound_within`,
    /// `{encoded,decoded}_bound_<n>` helpers, and `List::price`.
    Bounds,
    /// `Bounds`, plus each old public name (`worst_case_bytes`, `worst_case_heap`)
    /// as a one-line call of its new name: for a module another tree's
    /// hand-written code still calls by the old names. Helpers only under the new names.
    Both,
}

impl Names {
    fn encoded(self) -> &'static str {
        match self {
            Self::WorstCase => "worst_case_bytes",
            Self::Bounds | Self::Both => "encoded_bound",
        }
    }

    fn decoded(self) -> &'static str {
        match self {
            Self::WorstCase => "worst_case_heap",
            Self::Bounds | Self::Both => "decoded_bound",
        }
    }

    fn list_price(self) -> &'static str {
        match self {
            Self::WorstCase => "worst_case",
            Self::Bounds | Self::Both => "price",
        }
    }
}

/// `generate_named(schema, Names::WorstCase)`, until the contract.
#[must_use]
pub fn generate(schema: &Schema) -> Output {
    generate_named(schema, Names::WorstCase)
}

/// Writes a module under `names`.
#[must_use]
pub fn generate_named(schema: &Schema, names: Names) -> Output {
    let context = analysis::Context::new(schema);
    let mut rust = format!("// Generated by skein-codegen from {} {}. Do not edit.\n\n", schema.family, schema.version);
    let fields = schema
        .declarations
        .iter()
        .filter_map(|declaration| match declaration {
            Declaration::Record(record) => Some(record.fields.as_slice()),
            Declaration::Enum(_) => None,
        })
        .flatten();
    let types = fields.map(|field| &field.ty).collect::<Vec<_>>();
    if types.iter().any(|ty| uses_box(ty)) || has_boxed_variants(schema) {
        rust.push_str("use alloc::boxed::Box;\n");
    }
    if types.iter().any(|ty| uses_list(ty)) {
        rust.push_str("use skein_lib::List;\n");
    }
    rust.push('\n');
    emit_limits::emit(&context, &mut rust);
    emit_types::emit(&context, &mut rust);
    emit_codec::emit(&context, &mut rust);
    emit_bounds::emit(&context, names, &mut rust);
    emit_functions::split_bound_functions(&mut rust);
    let goldens = emit_tests::emit(&context, &mut rust);
    Output { rust, goldens }
}

fn has_boxed_variants(schema: &Schema) -> bool {
    schema.declarations.iter().any(|declaration| match declaration {
        Declaration::Enum(enumeration) => enumeration.variants.iter().any(|variant| variant.boxed),
        Declaration::Record(_) => false,
    })
}

